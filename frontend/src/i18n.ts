/**
 * Pure Übersetzungs-Regel — als eigene Funktion, damit der Test die
 * Fallback-Semantik mit beliebigen Wörterbüchern prüfen kann, ohne
 * localStorage zu stubben.
 */
export function uebersetze(
  schluessel: TextSchluessel,
  sprache: Sprache,
  en: Partial<Record<TextSchluessel, string>> = EN,
): string {
  if (sprache === 'en') {
    const u = en[schluessel];
    if (typeof u === 'string' && u.length > 0) return u;
  }
  return DE[schluessel];
}

/** Gewählte Sprache — alles außer ausdrücklichem 'en' ist Deutsch. */
export function sprachWahl(): Sprache {
  try {
    return localStorage.getItem('autotrd-lang') === 'en' ? 'en' : 'de';
  } catch {
    return 'de';
  }
}

/** Wahl speichern — das Anwenden (Neu-Rendern) entscheidet der Aufrufer. */
export function setzeSprache(sprache: Sprache): void {
  localStorage.setItem('autotrd-lang', sprache);
}

/** Der Übersetzer fürs UI: deutscher Text oder seine englische Fassung. */
export function t(schluessel: TextSchluessel): string {
  return uebersetze(schluessel, sprachWahl());
}

/**
 * Server-Fehlertext auflösen (Task #145): Die Cloud Functions werfen
 * `srv.*`-Codes als HttpsError-Message; hier werden sie in die gewählte
 * Sprache übersetzt. Dynamische Meldungen (Tranche 2) tragen GENAU EINEN
 * Wert hinter dem ersten `|` — er ersetzt `{0}` im Wörterbuchtext. Ein
 * einzelner Parameter ist Absicht: So bleibt ein Wert, der selbst `|`
 * enthält (z. B. eine durchgereichte Broker-Meldung), in einem Stück.
 * Alles, was KEIN bekannter Code ist — alte Functions-Stände,
 * Firebase-eigene Fehler, Helfer-Meldungen aus Tranche 3 —, wird
 * unverändert durchgereicht: nie eine leere Meldung, nie ein roher
 * Schlüssel für Texte, die das Wörterbuch nicht kennt.
 */
export function serverText(e: unknown): string {
  const roh = e instanceof Error ? e.message : String(e ?? '');
  /* Validierungs-Ablehnungen (Phase 3): `saveStrategy` joint mehrere
   * val.*-Codes mit ' · ' — jeder wird einzeln aufgelöst. Unbekannte
   * Segmente reicht valText unverändert durch. */
  if (roh.startsWith('val.')) {
    return roh.split(' · ').map(valText).join(' · ');
  }
  const trenn = roh.indexOf('|');
  const code = trenn < 0 ? roh : roh.slice(0, trenn);
  if (/^srv\.\w+$/.test(code) && code in DE) {
    const text = t(code as TextSchluessel);
    return trenn < 0 ? text : text.replaceAll('{0}', roh.slice(trenn + 1));
  }
  return roh;
}

/**
 * Validierungs-Code auflösen (Phase 3): `validateStrategy` (shared) liefert
 * `val.muster|feld|p1|p2` — anders als bei `srv.*` sind hier MEHRERE
 * Parameter erlaubt ({0}, {1}, {2}), weil Feldname und Grenzen nie ein `|`
 * enthalten. Was kein bekannter Code ist, geht unverändert durch — nie ein
 * roher Schlüssel im UI für Texte, die das Wörterbuch nicht kennt.
 */
export function valText(problem: string): string {
  const teile = problem.split('|');
  const code = teile[0]!;
  if (!/^val\.\w+$/.test(code) || !(code in DE)) return problem;
  let text = t(code as TextSchluessel);
  for (let i = 1; i < teile.length; i++) {
    text = text.replaceAll(`{${i - 1}}`, teile[i]!);
  }
  return text;
}
